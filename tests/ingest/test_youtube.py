"""YouTube transcript (sujet 3) - brick-free tests for the ref parse, json3 parse, weave and track pick.

Producer ≠ verifier (D75): an isolated audit checks this independently. These tests pin the deterministic
core - id extraction, json3 -> cues, verbatim restructuring + provenance mark, and manual-before-auto track
selection - with NO brick installed and no network (D126), so the logic is proven before yt-dlp is wired
(tests-before-code, D123). The json3 samples are hand-built to the documented schema; the real payload is
confronted at the pilot (F3).
"""

from __future__ import annotations

import json

import pytest

from mnemosyne.ingest import (
    parse_timedtext_json3,
    parse_youtube_ref,
    transcript_to_markdown,
    youtube_fetcher_if_available,
)
from mnemosyne.ingest.youtube_ytdlp import _select_track
from mnemosyne.ports import FetchedTranscript, TranscriptCue, TranscriptFetcher

VIDEO_ID = "dQw4w9WgXcQ"
AUTO_MARK = "**[Transcript auto-generated by YouTube - non-verbatim]**"


# --- parse_youtube_ref: every URL shape + bare id -> the canonical id, junk -> ValueError -----------------


@pytest.mark.parametrize(
    "ref",
    [
        "dQw4w9WgXcQ",
        "https://www.youtube.com/watch?v=dQw4w9WgXcQ",
        "https://youtube.com/watch?v=dQw4w9WgXcQ",
        "http://www.youtube.com/watch?v=dQw4w9WgXcQ",
        "https://m.youtube.com/watch?v=dQw4w9WgXcQ",
        "https://music.youtube.com/watch?v=dQw4w9WgXcQ",
        "https://www.youtube.com/watch?v=dQw4w9WgXcQ&list=PLabc&index=2&t=1s",
        "https://youtu.be/dQw4w9WgXcQ",
        "https://youtu.be/dQw4w9WgXcQ?t=43",
        "https://www.youtube.com/shorts/dQw4w9WgXcQ",
        "https://www.youtube.com/embed/dQw4w9WgXcQ",
        "https://www.youtube.com/live/dQw4w9WgXcQ",
        "https://www.youtube-nocookie.com/embed/dQw4w9WgXcQ",  # privacy-enhanced embed host
        "www.youtube.com/watch?v=dQw4w9WgXcQ",  # scheme-less
        "  https://youtu.be/dQw4w9WgXcQ  ",  # surrounding whitespace
    ],
)
def test_parse_ref_extracts_canonical_id(ref: str) -> None:
    assert parse_youtube_ref(ref) == VIDEO_ID


def test_parse_ref_accepts_id_with_url_safe_symbols() -> None:
    assert parse_youtube_ref("a_b-c1234XY") == "a_b-c1234XY"  # 11 chars, base64url alphabet


@pytest.mark.parametrize(
    "ref",
    [
        "",
        "short",  # not 11 chars, not a URL
        "https://vimeo.com/76979871",  # wrong host
        "https://example.com/watch?v=dQw4w9WgXcQ",  # id present but wrong host
        "https://www.youtube.com/watch?v=",  # empty v
        "https://www.youtube.com/watch?v=tooLong12345",  # >11 chars
        "https://www.youtube.com/playlist?list=PLabc",  # a playlist, no video
        "https://www.youtube.com/",  # bare host
    ],
)
def test_parse_ref_rejects_junk(ref: str) -> None:
    with pytest.raises(ValueError):
        parse_youtube_ref(ref)


# --- parse_timedtext_json3: events -> verbatim cues, skipping empty spacers --------------------------------


def test_json3_concatenates_segments_and_scales_time() -> None:
    payload = json.dumps(
        {
            "events": [
                {"tStartMs": 0, "segs": [{"utf8": "Hello"}, {"utf8": " world"}]},
                {"tStartMs": 1500, "segs": [{"utf8": "next"}]},
            ]
        }
    )
    cues = parse_timedtext_json3(payload)
    assert cues == (
        TranscriptCue(0.0, "Hello world"),
        TranscriptCue(1.5, "next"),
    )


def test_json3_skips_events_without_segs_or_text() -> None:
    payload = json.dumps(
        {
            "events": [
                {"tStartMs": 0},  # no segs (a window-clear event)
                {"tStartMs": 100, "segs": [{"utf8": "\n"}]},  # whitespace only
                {"tStartMs": 200, "segs": [{"utf8": "real"}]},
            ]
        }
    )
    assert parse_timedtext_json3(payload) == (TranscriptCue(0.2, "real"),)


def test_json3_empty_payload_yields_no_cues() -> None:
    assert parse_timedtext_json3("{}") == ()


def test_json3_raises_on_non_json() -> None:
    # a fetch that returned garbage must fail loud, never a silent empty transcript
    with pytest.raises(json.JSONDecodeError):
        parse_timedtext_json3("<html>not json</html>")


def test_json3_rejects_valid_json_that_is_not_an_object() -> None:
    # a JSON array (e.g. an error page parsed as JSON) is valid JSON but not json3 - fail loud, not AttributeError
    with pytest.raises(ValueError):
        parse_timedtext_json3("[]")


# --- transcript_to_markdown: provenance header + verbatim body, auto MARKED -----------------------------


def _transcript(
    *, auto: bool, cues: tuple[TranscriptCue, ...], lang: str = "fr"
) -> FetchedTranscript:
    return FetchedTranscript(
        video_id=VIDEO_ID,
        title="My video",
        uploader="A channel",
        webpage_url=f"https://www.youtube.com/watch?v={VIDEO_ID}",
        language=lang,
        auto_generated=auto,
        cues=cues,
    )


def test_markdown_carries_provenance_and_verbatim_words() -> None:
    md = transcript_to_markdown(
        _transcript(auto=False, cues=(TranscriptCue(0.0, "the brown fox"),))
    )
    assert md.startswith("# My video\n")
    assert "> **Source YouTube** — A channel" in md
    assert f"> https://www.youtube.com/watch?v={VIDEO_ID}" in md
    assert "> Langue : fr" in md
    assert "> Langue : fr\n\nthe brown fox" in md  # blank line separates provenance from body
    assert "the brown fox" in md  # verbatim, not paraphrased
    assert AUTO_MARK not in md  # manual subtitles are NOT marked auto


def test_markdown_marks_auto_captions_non_verbatim() -> None:
    md = transcript_to_markdown(_transcript(auto=True, cues=(TranscriptCue(0.0, "hi"),)))
    assert AUTO_MARK in md


def test_markdown_dedupes_consecutive_repeats() -> None:
    # auto-captions re-emit the previous line (rolling window); the exact consecutive repeat is dropped
    cues = (
        TranscriptCue(0.0, "a sentence"),
        TranscriptCue(1.0, "a sentence"),
        TranscriptCue(2.0, "then another one"),
    )
    body = transcript_to_markdown(_transcript(auto=True, cues=cues))
    assert body.count("a sentence") == 1
    assert "then another one" in body


def test_markdown_keeps_manual_repeats_verbatim() -> None:
    # MINEUR-5: a repeat in MANUAL subtitles is the author's intent (a refrain) - kept verbatim (P3), not deduped
    cues = (TranscriptCue(0.0, "na"), TranscriptCue(1.0, "na"), TranscriptCue(2.0, "na"))
    body = transcript_to_markdown(_transcript(auto=False, cues=cues))
    assert body.count("na") == 3


def test_markdown_groups_paragraphs_by_time_window() -> None:
    # cues more than the 30s window apart land in separate paragraphs (restructured, not reworded)
    cues = (TranscriptCue(0.0, "start"), TranscriptCue(45.0, "much later"))
    md = transcript_to_markdown(_transcript(auto=False, cues=cues))
    assert "start\n\nmuch later" in md


def test_markdown_handles_no_subtitles_honestly() -> None:
    md = transcript_to_markdown(_transcript(auto=False, cues=(), lang=""))
    assert "_(no subtitles available)_" in md
    assert "# My video" in md  # provenance still present


def test_markdown_auto_generated_but_empty_marks_and_notes() -> None:
    # an auto-caption source that yielded no cues: BOTH the ASR mark and the honest empty note appear
    md = transcript_to_markdown(_transcript(auto=True, cues=(), lang="fr"))
    assert AUTO_MARK in md
    assert "_(no subtitles available)_" in md


def test_markdown_metadata_is_zero_trust_one_line() -> None:
    # D100-3: an untrusted title/channel with newlines + markdown can't inject a heading or a blockquote -
    # each metadata field is collapsed to one line (the sujet-2 zero-trust discipline applied to provenance)
    poisoned = FetchedTranscript(
        video_id=VIDEO_ID,
        title="Real title\n# Fake title injected\n## Subtitle",
        uploader="channel\n> injection",
        webpage_url=f"https://www.youtube.com/watch?v={VIDEO_ID}",
        language="fr",
        auto_generated=False,
        cues=(TranscriptCue(0.0, "body"),),
    )
    lines = transcript_to_markdown(poisoned).splitlines()
    assert lines[0] == "# Real title # Fake title injected ## Subtitle"
    assert sum(1 for line in lines if line.startswith("# ")) == 1  # no injected extra H1
    assert "> **Source YouTube** — channel > injection" in lines


# --- _select_track: manual before auto, in language order, json3 only -----------------------------------

_JSON3 = {"ext": "json3", "url": "https://timedtext/j"}
_VTT = {"ext": "vtt", "url": "https://timedtext/v"}


def test_select_prefers_manual_over_auto() -> None:
    picked = _select_track({"fr": [_JSON3]}, {"fr": [_JSON3]}, ("fr", "en"))
    assert picked is not None
    assert picked.auto_generated is False and picked.language == "fr"


def test_select_falls_back_to_auto_when_no_manual() -> None:
    picked = _select_track({}, {"fr": [_JSON3]}, ("fr", "en"))
    assert picked is not None
    assert picked.auto_generated is True and picked.language == "fr"


def test_select_manual_wins_even_in_less_preferred_language() -> None:
    # a manual EN track beats an auto FR track - verbatim trumps language preference
    picked = _select_track({"en": [_JSON3]}, {"fr": [_JSON3]}, ("fr", "en"))
    assert picked is not None
    assert picked.auto_generated is False and picked.language == "en"


def test_select_respects_language_order_within_a_kind() -> None:
    picked = _select_track({"fr": [_JSON3], "en": [_JSON3]}, {}, ("fr", "en"))
    assert picked is not None and picked.language == "fr"


def test_select_manual_regional_variant_beats_auto_caption() -> None:
    # MAJEUR-1: a MANUAL en-US track must win over an auto fr caption for languages=("fr","en") - the exact
    # bug where regional variants (en-US, fr-FR) were missed and the ASR auto-caption was served instead
    picked = _select_track({"en-US": [_JSON3]}, {"fr": [_JSON3]}, ("fr", "en"))
    assert picked is not None
    assert picked.auto_generated is False and picked.language == "en-US"


def test_select_prefers_exact_language_over_regional_variant() -> None:
    picked = _select_track({"en": [_JSON3], "en-GB": [_JSON3]}, {}, ("en",))
    assert picked is not None and picked.language == "en"


def test_select_ignores_non_json3_and_returns_none() -> None:
    assert _select_track({"fr": [_VTT]}, {"en": [_VTT]}, ("fr", "en")) is None
    assert _select_track({}, {}, ("fr", "en")) is None


# --- port conformance ------------------------------------------------------------------------------------


def test_fetched_transcript_is_immutable() -> None:
    t = _transcript(auto=False, cues=())
    with pytest.raises((AttributeError, TypeError)):
        t.title = "other"  # type: ignore[misc]


def test_fake_fetcher_satisfies_the_protocol() -> None:
    class _FakeFetcher:
        def fetch(self, ref: str) -> FetchedTranscript:
            return _transcript(auto=False, cues=(TranscriptCue(0.0, parse_youtube_ref(ref)),))

    fetcher = _FakeFetcher()
    assert isinstance(fetcher, TranscriptFetcher)  # runtime_checkable Protocol conformance
    assert fetcher.fetch(VIDEO_ID).cues[0].text == VIDEO_ID


# --- youtube_fetcher_if_available: best-effort wiring, deterministic on either brick state --------------


def test_youtube_fetcher_none_when_brick_absent(monkeypatch: pytest.MonkeyPatch) -> None:
    # the OPTIONAL yt-dlp brick is not installed => connect_ytdlp raises ImportError => degrade to None
    # (never a crash), so real_runtime and the suite stay green with no brick (D126). Simulated so the test
    # is deterministic whether or not yt-dlp happens to be installed in the env.
    def _boom() -> object:
        raise ImportError("yt-dlp not installed")

    monkeypatch.setattr("mnemosyne.ingest.youtube_ytdlp.connect_ytdlp", _boom)
    assert youtube_fetcher_if_available() is None


def test_youtube_fetcher_returns_adapter_when_brick_present(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    # brick present => the adapter is returned (wiring the CAPABILITY only - a fetch still needs the Guard's
    # allow-list, deny-by-default). Mocked so no real yt-dlp / network is touched.
    sentinel = object()
    monkeypatch.setattr("mnemosyne.ingest.youtube_ytdlp.connect_ytdlp", lambda: sentinel)
    assert youtube_fetcher_if_available() is sentinel

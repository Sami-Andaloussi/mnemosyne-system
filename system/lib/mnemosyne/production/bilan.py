"""THE END-OF-SESSION SUMMARY (workstream 1 · B5, the flagship project's inventions 1 + 2) — the pure JUDGE.

> The operator, 2026-07-30, verbatim: *"end of session, here's what we did and here's what's left
> to do [...] and it must not vanish, not even after a post-compaction. And that's supposed to be
> part of the whole of Mnemosyne."*

The flagship project solved this alone, with **two** inventions that only have value together:

1. **A STABLE address**, a single copy, overwritten every time — the history lives in git, never
   one more dated file (otherwise it becomes a museum of the build).
2. **The state is PULLED, it is never re-copied.** The flagship project, word for word: *"asking 'where am I'
   REWRITES the table. There is no path to read it stale."*

**WHY BOTH, AND NOT THE FIRST ALONE.** The resumption document is **the only one in the repo
whose author writes the final version BEFORE the end of what it describes** — that is structural,
not negligence. Measured on 2026-07-31: a committed summary said "twelve phases" when the session
had actually produced thirteen, and **nothing flagged it**. *A stale resumption document is WORSE
than none at all: it reads as up to date.*

## Where the line falls, inside the file itself

* **The PULLED block** (between :data:`MARQUEUR_DEBUT` and :data:`MARQUEUR_FIN`) is **generated**.
  Nobody edits it; `make bilan` rewrites it, `make bilan VERIFIER=1` refuses when it has drifted,
  and the tick reports it at the start of the next session — that is, **at the exact moment one is
  about to believe it**.
* **The prose** — what was done, what is waiting for the operator — is **hand-written**, and the
  code never touches it. It is never generated: it is the session's own judgement.

**What this module does NOT hold, and it must be said**: nothing here verifies that the
*prose* is up to date. A summary whose numbers are fresh and whose narrative lies would still pass
green. The only barrier against that remains the gesture — **re-pulling the summary right before
compacting**, never once one believes the work is done. This is an admission, not a disguised
barrier.

The module is a **pure judge**: no measurement is taken here, it is **injected** by
:mod:`mnemosyne.runtime.bilan_run` at the edge. Prose is French by design in this repo's own
convention (D117) - this public-mirror copy is translated into English throughout.
"""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass

#: The STABLE address, relative to the repo root. A single copy, overwritten — the history lives
#: in git. `docs/` and not the root: it is neither read at startup by the tooling, nor written to
#: permanently (the three-branch test from `CLAUDE.md`) — it is the kind of meta-doc the door
#: points to.
CHEMIN = "docs/FIN-DE-SESSION.md"

#: The bounds of the generated block. They sit inside an HTML comment: invisible on a plain read,
#: and **a comment is never a declaration** — the lesson B4 paid for two hours earlier.
MARQUEUR_DEBUT = "<!-- PULLED STATE · START — generated by `make bilan`, do not edit by hand -->"
MARQUEUR_FIN = "<!-- PULLED STATE · END -->"


@dataclass(frozen=True, slots=True)
class Mesure:
    """One figure AND the command that produces it. Never one without the other.

    ``commande`` is **mandatory** and :func:`rendre_l_etat` refuses a measurement that does not
    carry one: *a count without its command is a memory.* This is what lets a reader redo the
    measurement instead of taking the file's word for it."""

    quoi: str
    valeur: str
    commande: str


class BilanRefus(Exception):
    """A NAMED refusal — the file is never written half-done."""


def rendre_l_etat(mesures: Iterable[Mesure], *, mesure_le: str) -> str:
    """The generated block, bounds included. ``mesure_le`` is the date of THIS measurement, not another's."""
    table = tuple(mesures)
    if not table:
        raise BilanRefus(
            "no measurement to engrave: an EMPTY state block reads exactly like a HEALTHY one. "
            "The summary refuses rather than writing a page that asserts nothing."
        )
    muettes = [m.quoi for m in table if not m.commande.strip()]
    if muettes:
        raise BilanRefus(
            f"{len(muettes)} measurement(s) with no command: {', '.join(muettes)}. A count with no "
            "command is a memory — the reader must be able to redo it, not take your word for it."
        )
    lignes = [
        MARQUEUR_DEBUT,
        "",
        f"**Measured on {mesure_le}.** Every figure carries its command: never copy it,",
        "**pull it again**. This block is rewritten by `make bilan` — editing it by hand makes it lie.",
        "",
        "| what is measured | at the last pull | the command that produces it |",
        "|---|---|---|",
    ]
    lignes.extend(f"| {m.quoi} | {m.valeur} | `{m.commande}` |" for m in table)
    lignes.extend(("", MARQUEUR_FIN))
    return "\n".join(lignes)


def remplacer_l_etat(document: str, bloc: str) -> str:
    """Rewrite the generated block and **nothing else** — the prose is never touched.

    Refuses rather than guessing: bounds missing, duplicated, or in the wrong order. A lost bound
    would write the state to the wrong place, or overwrite hand-written prose — and *a rewrite
    loses what it does not recopy*."""
    for borne, nom in ((MARQUEUR_DEBUT, "start"), (MARQUEUR_FIN, "end")):
        combien = document.count(borne)
        if combien != 1:
            raise BilanRefus(
                f"bound `{nom}` present {combien} times instead of exactly one. The summary "
                "refuses: writing the state without knowing where it starts would overwrite "
                "hand-written prose."
            )
    i = document.index(MARQUEUR_DEBUT)
    j = document.index(MARQUEUR_FIN) + len(MARQUEUR_FIN)
    if j <= i:
        raise BilanRefus("the bounds are inverted: the end precedes the start.")
    return document[:i] + bloc + document[j:]


def etat_courant(document: str) -> str:
    """The generated block exactly as WRITTEN in the file — to compare against a fresh pull."""
    for borne in (MARQUEUR_DEBUT, MARQUEUR_FIN):
        if document.count(borne) != 1:
            raise BilanRefus("bound missing or duplicated: the written state cannot be read.")
    i = document.index(MARQUEUR_DEBUT)
    j = document.index(MARQUEUR_FIN) + len(MARQUEUR_FIN)
    return document[i:j]


def premiere_ligne_qui_differe(document: str, bloc_frais: str) -> str | None:
    """The FIRST line where the written state and a fresh pull diverge — ``None`` if they agree.

    **"It has drifted" does not say WHERE, and a refusal nobody can act on gets bypassed.** The
    refusal named the file and the remedy; faced with a 16-line block, the reader cannot tell
    whether a counter moved by 1 or half the table is wrong — so they re-run the command without
    looking, and *a refusal obeyed without being read teaches nothing*.

    **WHY A SINGLE PAIRWISE WALK IS ENOUGH — this is a REACHABILITY argument, not an economy.**
    I had first written three branches (line changed · block too short · too long), announcing
    "here is the class." **The last two are UNREACHABLE**: :func:`etat_courant` returns the block
    WITH its markers and :func:`rendre_l_etat` carries them too (*measured*), so the two blocks
    always end on the same line and **neither can be a prefix of the other**. A length that
    differs necessarily makes a pair appear, at the marker's rank, where one side carries the
    marker and the other carries content. *Two dead branches presented as a closed class are worth
    less than zero: they make the hole look covered.*

    The number returned is the DOCUMENT's, not the block's: it is the one the editor displays.
    """
    ecrit = etat_courant(document)
    if ecrit == bloc_frais:
        return None
    decalage = document[: document.index(MARQUEUR_DEBUT)].count("\n")
    for rang, (avant, apres) in enumerate(zip(ecrit.splitlines(), bloc_frais.splitlines())):
        if avant != apres:
            return (
                f"line {decalage + rang + 1} — written: « {avant.strip()} » · "
                f"fresh: « {apres.strip()} »"
            )
    # Unreachable as long as both blocks carry their markers (see the docstring). If that ever
    # stops being true, this branch REFUSES and says so — it never returns `None`, which would
    # mean "no drift" on a real drift: the loss would be SILENT.
    return (
        "the block has DRIFTED by its LENGTH without a single line differing — "
        f"written {len(ecrit.splitlines())} lines, fresh {len(bloc_frais.splitlines())}"
    )


def a_derive(document: str, bloc_frais: str) -> bool:
    """True when the written state no longer says what a fresh pull says.

    **THE DATE COUNTS AS A DRIFT, AND THAT IS INTENTIONAL.** A summary measured yesterday can
    carry the same figures and still be wrong: what matters is *when* it was pulled."""
    return etat_courant(document) != bloc_frais

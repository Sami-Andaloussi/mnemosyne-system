"""Provenance marks - the ONE home of "this line was INSERTED by an ingestion automatism, not the source".

An enrichment step can add lines to a raw ``.md`` that are NOT the author's words:

* a VISION model's figure caption (sujet 2, :func:`mnemosyne.ingest.caption.weave_captions` writes
  ``> **[Figure described by a model]**  <one-line description>`` in place of a Docling figure hole);
* YouTube's ASR **auto-caption** header (sujet 3, :func:`mnemosyne.ingest.youtube.transcript_to_markdown`
  writes ``> **[Transcript auto-generated by YouTube - non-verbatim]**`` above an auto-captioned body);
* a VECTOR figure's EXTRACTED data (sujet E, :func:`mnemosyne.ingest.figure_extract.describe_vector_figure`
  writes ``> **[Figure - data extracted from the vector plot]**  <one-line structured read-out>`` in place of
  a Docling figure hole, reconstructed from the PDF's OWN vector primitives - axes text, bar/point profile).

All three are MARKED so a reader SEES them - but the verbatim floor (:func:`mnemosyne.production.keep_verbatim`)
must ALSO see them, or a line copied into a fiche's P3 would be promoted to "the source's own words": a VLM
hallucination - or our own figure characterization - blessed as the author's verbatim (the failure this module
exists to make impossible, D100 / [[restructure-not-reformulate]]). :func:`strip_inserted_lines` removes those
lines from the source BEFORE the substring test, so a passage quoting one can never survive the floor.

**The three marks carry different STAKES (and that difference is the point).** A vision caption is inserted IN
THE MIDDLE of the author's text and is potentially INVENTED - masking it is a hard fidelity barrier. A YouTube
auto-caption mark is a HEADER line: the transcript body below it stays the legitimate source (a transcript IS
the ingested source of truth, its ASR words distilled verbatim like any transcript, D115) - we strip only the
header annotation so it is not itself quoted as content. The figure-data mark is the SUBTLE one: its content is
DETERMINISTIC extraction, not invented (even the axis labels it quotes ARE the PDF's real characters, genuine
verbatim) - yet we mask the WHOLE line anyway, fail-closed, because the read-out also carries OUR
characterization ("histogram, bell-shaped, ~20 bins"), which is our prose and never the author's; we give up
promoting a few genuine axis labels to be CERTAIN our prose can never pass as verbatim. All three obey the same
rule, so they live in the same list.

**Exactly what the guarantee covers (honest scope, D100 / F3).** After stripping, only AUTHOR lines remain, so
a passage can never quote inserted text - that is the invariant, and it holds regardless of the source's
Unicode normal form (the match is NFC-folded, so a decomposed OCR/PDF source cannot smuggle a mark past the
test). Two caveats, both bounded and neither a promotion of inserted text: (a) the mask is LINE-scoped, so it
relies on a mark staying on ONE line - an invariant the producers hold (``weave_captions`` and the figure
read-out both collapse to a single line; the YouTube mark is one header line); (b) removing a figure line
re-joins the real text on either side, so a passage that SKIPS a figure (quoting the author before and after it
as if contiguous) can match - a relaxed contiguity across a figure boundary, but still only the author's own
words, never inserted text.

Single source of every mark (anti-drift, [[consolidate-crosscutting-rules]] / [[contract-single-source-emit]]):
the PRODUCERS (``ingest`` - weave_captions, transcript_to_markdown, figure_extract) and the VERIFIER
(``production`` - keep_verbatim, hence the juge that reuses it) all import from HERE, so a mark changed in one
place cannot silently split them. This is a LEAF module (only stdlib imports) so both layers import it without
pulling a package or risking an import cycle. Code & docstrings English (D117); the marks themselves used to be
French in the operator's own deployment - they land in the produced ``.md`` (D33 / D117 produit).

Decisions: D100 (the guarantee is in the code, never the model's good behaviour or an upstream assumption)  -
restructure-not-reformulate (P3 = the source's words ONLY)  -  D143 (verbatim discipline)  -  D85 (fail-open).
"""

from __future__ import annotations

import unicodedata
from typing import Final

#: The vision figure caption mark (sujet 2). The single source - ``ingest.caption`` imports it to WRITE the
#: line, ``keep_verbatim`` (via :data:`INSERTED_MARKS`) imports it to REFUSE the line as verbatim.
FIGURE_CAPTION_MARK: Final = "**[Figure described by a model]**"

#: The YouTube ASR auto-caption header mark (sujet 3). Flags a transcript as YouTube's guess, not human
#: verbatim; masked only so the header annotation is not itself quoted as content (the body stays the source).
AUTO_CAPTION_MARK: Final = "**[Transcript auto-generated by YouTube - non-verbatim]**"

#: The extracted-vector-figure mark (sujet E). Flags a one-line structured read-out reconstructed from a PDF
#: figure's OWN vector primitives (axes text + bar/point profile) - deterministic, not a model guess, but still
#: not the author's prose, so masked from the verbatim floor (fail-closed: our characterization is never
#: promoted, even though the axis labels it quotes are themselves genuine verbatim).
FIGURE_DATA_MARK: Final = "**[Figure - data extracted from the vector plot]**"

#: The frontier (cloud VLM) figure caption mark (sujet G / niveau 3). Like :data:`FIGURE_CAPTION_MARK` it is a
#: MODEL guess - but from a frontier model reached by a HUMAN-triggered, Guard-mediated egress, used ONLY on the
#: abstract charts where the local vector path + 7B both fail. A DISTINCT mark so a cloud read-out is traceable
#: and countable (what left the machine), and masked from the verbatim floor exactly like the others.
FIGURE_CLOUD_MARK: Final = "**[Figure described by a frontier model]**"

#: The EXTRACTED-IMAGE mark (arc D). Flags a line carrying the figure ITSELF - a ``![...](....png)`` link to the
#: PNG Docling rendered from the PDF - rather than any description of it. It is the only figure path with NO
#: model and NO characterization: the pixels are the author's own figure. Masked from the verbatim floor all
#: the same, because the LINE is ours (the markdown syntax, the "Figure N" alt, our path) even though what it
#: points at is genuine - fail-closed, exactly like :data:`FIGURE_DATA_MARK`.
FIGURE_IMAGE_MARK: Final = "**[Figure - image extracted from the PDF]**"

#: Every mark flagging a line as INSERTED by an ingestion automatism (a model, OR a deterministic extraction) -
#: never the author's own words. Extensible: a new enrichment stage adds its mark HERE and
#: :func:`strip_inserted_lines` - thus keep_verbatim and the juge - cover it for free (one rule, one edit,
#: everywhere).
INSERTED_MARKS: Final = (
    FIGURE_CAPTION_MARK,
    AUTO_CAPTION_MARK,
    FIGURE_DATA_MARK,
    FIGURE_CLOUD_MARK,
    FIGURE_IMAGE_MARK,
)

#: The marks in NFC normal form. keep_verbatim NFC-folds the source before its substring test, and OCR / PDF
#: sources are commonly DECOMPOSED (NFD, cf. ``distillation._normalize_ws``): so the mark test must NFC-fold
#: too, or a decomposed-accent source would slip a marked line past the strip and back into the verbatim compare
#: (D100 defense in depth - the barrier must not depend on the source's normal form).
_MARKS_NFC: Final = tuple(unicodedata.normalize("NFC", mark) for mark in INSERTED_MARKS)


def _carries_mark(text: str) -> bool:
    """Whether ``text`` contains an inserted-line mark, compared in NFC so the check is normalization-proof."""
    normalized = unicodedata.normalize("NFC", text)
    return any(mark in normalized for mark in _MARKS_NFC)


def strip_inserted_lines(source: str) -> str:
    """Return ``source`` with every LINE carrying an inserted-line mark removed (D100).

    So the verbatim floor compares a candidate passage against the AUTHOR's text only: a vision caption, a
    YouTube ASR header, or a vector-figure read-out - inserted by an enrichment automatism, never the source's
    own words - is not a substring of the stripped source, so a passage quoting it is DROPPED, and inserted
    text can never be promoted to the source's verbatim. The mark test is NFC-folded (:func:`_carries_mark`),
    so a decomposed (NFD) OCR/PDF source cannot smuggle a marked line past it. Surviving lines are re-joined
    with ``\\n`` (the original bytes kept - only marked lines are dropped, nothing is re-encoded), which the
    floor's whitespace-normalization later collapses to a single space.

    A source with no such mark - every pre-enrichment raw, i.e. the entire current corpus - is returned
    UNCHANGED (same object) via the fast path, so :func:`keep_verbatim` stays byte-identical to before this
    stage until an enrichment actually inserts a line (zero regression). See the module docstring for the two
    bounded caveats (line-scoped mask; relaxed contiguity across a removed figure) - neither can promote
    inserted text, which is the guarantee. Content-agnostic beyond the literal, NFC-folded mark."""
    if not _carries_mark(source):
        return source  # fast path + explicit no-op on every pre-enrichment source (zero regression)
    return "\n".join(line for line in source.split("\n") if not _carries_mark(line))
